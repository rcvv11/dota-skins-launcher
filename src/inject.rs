//! Memory mode: the same list of swaps as the file mode, but nothing is
//! written to the game folder. The table goes to `%APPDATA%\dota-skins\model_swap.cfg`,
//! and `changer.dll` (native/changer.cpp), injected into dota2.exe, swaps
//! resource files as they load. This is the only module that writes into another
//! process.

#![allow(non_snake_case)]

use std::collections::{HashMap, HashSet};
use std::ffi::c_void;
use std::path::{Path, PathBuf};
use std::time::{Duration, Instant};

use crate::extract::Req;
use crate::win;

pub const DLL_NAME: &str = "changer.dll";

pub fn config_path() -> PathBuf {
    crate::config::app_dir().join("model_swap.cfg")
}

pub fn log_path() -> PathBuf {
    crate::config::app_dir().join("model_swap.log")
}

/// changer.dll next to the launcher (or in dist\ / native\ of the repo).
pub fn find_dll() -> Option<PathBuf> {
    let exe = std::env::current_exe().ok()?;
    exe.ancestors()
        .skip(1)
        .take(4)
        .flat_map(|d| [d.join(DLL_NAME), d.join("dist").join(DLL_NAME), d.join("native").join(DLL_NAME)])
        .find(|p| p.is_file())
}

/// `x.vmdl_c` -> `x.vmdl`: the DLL keys rules by the source path.
fn source_path(compiled: &str) -> &str {
    compiled.strip_suffix("_c").unwrap_or(compiled)
}

/// Rules `<default file>|<item file>`, first override of a file wins.
/// The table's lines `dst|src`, and `dst|src|npc_dota_hero_x,...` for a hero
/// item's swap (`heroes`: item name -> the npc names of its heroes): in a match
/// the DLL applies those only to the hero you play, the others keep their own look.
pub fn config_text(reqs: &[Req], heroes: &HashMap<String, Vec<String>>) -> (String, usize) {
    let mut seen = HashSet::new();
    let mut text = String::from("# generated by dota-skins-launcher\n");
    // language of the buttons in Dota's interface (DLL)
    text.push_str(&format!("lang|{}\n", crate::i18n::code()));
    for r in reqs {
        let (dst, src) = (source_path(&r.dst), source_path(&r.src));
        if dst.eq_ignore_ascii_case(src) || !seen.insert(dst.to_ascii_lowercase()) {
            continue;
        }
        text.push_str(dst);
        text.push('|');
        text.push_str(src);
        if let Some(npcs) = heroes.get(&r.id).filter(|n| !n.is_empty()) {
            text.push('|');
            text.push_str(&npcs.join(","));
        }
        text.push('\n');
    }
    (text, seen.len())
}

/// Written via a temp file + rename: a running DLL re-reads the table as soon
/// as it changes and must never see it half-written.
pub fn write_config(reqs: &[Req], glows: &[String], heroes: &HashMap<String, Vec<String>>) -> Result<usize, String> {
    let (mut text, n) = config_text(reqs, heroes);
    for g in glows {
        text.push_str(g);
        text.push('\n');
    }
    let path = config_path();
    let tmp = path.with_extension("cfg.tmp");
    std::fs::create_dir_all(crate::config::app_dir())
        .and_then(|_| std::fs::write(&tmp, text))
        .and_then(|_| std::fs::rename(&tmp, &path))
        .map_err(|e| crate::trf!("не удалось записать {}: {e}", "could not write {}: {e}", path.display()))?;
    Ok(n)
}

pub fn wait_for_process(exe: &str, timeout: Duration) -> Option<u32> {
    let start = Instant::now();
    while start.elapsed() < timeout {
        if let Some(&pid) = win::find_processes(exe).first() {
            return Some(pid);
        }
        std::thread::sleep(Duration::from_millis(250));
    }
    None
}

const PROCESS_CREATE_THREAD: u32 = 0x0002;
const PROCESS_VM_OPERATION: u32 = 0x0008;
const PROCESS_VM_WRITE: u32 = 0x0020;
const PROCESS_QUERY_INFORMATION: u32 = 0x0400;
const MEM_COMMIT: u32 = 0x1000;
const MEM_RESERVE: u32 = 0x2000;
const MEM_RELEASE: u32 = 0x8000;
const PAGE_READWRITE: u32 = 0x04;
const WAIT_OBJECT_0: u32 = 0;

#[link(name = "kernel32")]
extern "system" {
    fn OpenProcess(access: u32, inherit: i32, pid: u32) -> isize;
    fn VirtualAllocEx(proc: isize, addr: *mut c_void, size: usize, kind: u32, protect: u32) -> *mut c_void;
    fn VirtualFreeEx(proc: isize, addr: *mut c_void, size: usize, kind: u32) -> i32;
    fn WriteProcessMemory(proc: isize, addr: *mut c_void, buf: *const c_void, size: usize, written: *mut usize) -> i32;
    fn GetModuleHandleW(name: *const u16) -> isize;
    fn GetProcAddress(module: isize, name: *const u8) -> *mut c_void;
    fn CreateRemoteThread(
        proc: isize,
        attrs: *mut c_void,
        stack: usize,
        start: *mut c_void,
        param: *mut c_void,
        flags: u32,
        tid: *mut u32,
    ) -> isize;
    fn WaitForSingleObject(h: isize, ms: u32) -> u32;
    fn GetExitCodeThread(h: isize, code: *mut u32) -> i32;
    fn CloseHandle(h: isize) -> i32;
    fn GetLastError() -> u32;
}

struct Handle(isize);

impl Drop for Handle {
    fn drop(&mut self) {
        unsafe { CloseHandle(self.0) };
    }
}

/// Loads `dll` into process `pid` with a remote `LoadLibraryW` call.
pub fn inject(pid: u32, dll: &Path) -> Result<(), String> {
    let path = win::wide(&dll.to_string_lossy());
    let bytes = path.len() * 2;
    unsafe {
        let proc = OpenProcess(
            PROCESS_CREATE_THREAD | PROCESS_QUERY_INFORMATION | PROCESS_VM_OPERATION | PROCESS_VM_WRITE,
            0,
            pid,
        );
        if proc == 0 {
            return Err(crate::trf!("нет доступа к dota2.exe (ошибка {})", "no access to dota2.exe (error {})", GetLastError()));
        }
        let proc = Handle(proc);

        let remote = VirtualAllocEx(proc.0, std::ptr::null_mut(), bytes, MEM_COMMIT | MEM_RESERVE, PAGE_READWRITE);
        if remote.is_null() {
            return Err(crate::trf!("VirtualAllocEx: ошибка {}", "VirtualAllocEx: error {}", GetLastError()));
        }
        let result = (|| {
            if WriteProcessMemory(proc.0, remote, path.as_ptr().cast(), bytes, std::ptr::null_mut()) == 0 {
                return Err(crate::trf!("WriteProcessMemory: ошибка {}", "WriteProcessMemory: error {}", GetLastError()));
            }
            let kernel32 = GetModuleHandleW(win::wide("kernel32.dll").as_ptr());
            let load_library = GetProcAddress(kernel32, b"LoadLibraryW\0".as_ptr());
            if load_library.is_null() {
                return Err(crate::tr!("LoadLibraryW не найдена", "LoadLibraryW not found").into());
            }
            let thread = CreateRemoteThread(proc.0, std::ptr::null_mut(), 0, load_library, remote, 0, std::ptr::null_mut());
            if thread == 0 {
                return Err(crate::trf!("CreateRemoteThread: ошибка {}", "CreateRemoteThread: error {}", GetLastError()));
            }
            let thread = Handle(thread);
            if WaitForSingleObject(thread.0, 15_000) != WAIT_OBJECT_0 {
                return Err(crate::tr!("dota2.exe не загрузила DLL за 15 с", "dota2.exe did not load the DLL in 15 s").into());
            }
            let mut module = 0u32;
            GetExitCodeThread(thread.0, &mut module);
            if module == 0 {
                return Err(crate::trf!("dota2.exe не смогла загрузить {}", "dota2.exe could not load {}", dll.display()));
            }
            Ok(())
        })();
        VirtualFreeEx(proc.0, remote, 0, MEM_RELEASE);
        result
    }
}

/// Starts Dota and injects the DLL as soon as the process appears, so the hook
/// is in place before hero resources load.
pub fn launch_and_inject(dota_exe: &str, args: &str, step: &dyn Fn(&str)) -> Result<String, String> {
    let dll = find_dll().ok_or_else(|| crate::trf!("не найден {DLL_NAME} рядом с лаунчером", "{DLL_NAME} not found next to the launcher"))?;
    step(crate::tr!("Запускаю Dota 2…", "Starting Dota 2…"));
    crate::dota::launch(dota_exe, args)?;
    step(crate::tr!("Жду dota2.exe…", "Waiting for dota2.exe…"));
    let pid = wait_for_process("dota2.exe", Duration::from_secs(120))
        .ok_or(crate::tr!("dota2.exe не запустилась за 2 минуты", "dota2.exe did not start within 2 minutes"))?;
    step(crate::tr!("Внедряю changer.dll…", "Injecting changer.dll…"));
    inject(pid, &dll)?;
    Ok(crate::trf!("Dota 2 запущена с подменой в памяти (лог: {})", "Dota 2 started with memory swapping (log: {})", log_path().display()))
}

/// Dota is already running: the DLL picks up the rewritten table by itself;
/// inject it in case Dota was started without the launcher (a second
/// `LoadLibraryW` of a loaded DLL does nothing).
pub fn apply_to_running() -> Result<String, String> {
    let dll = find_dll().ok_or_else(|| crate::trf!("не найден {DLL_NAME} рядом с лаунчером", "{DLL_NAME} not found next to the launcher"))?;
    let pid = *win::find_processes("dota2.exe").first().ok_or(crate::tr!("dota2.exe уже не запущена", "dota2.exe is no longer running"))?;
    inject(pid, &dll)?;
    Ok(crate::tr!("Применено без перезапуска: модели, которые уже загружены, сменятся со следующей загрузки \
        героя (например, в следующем матче)", "Applied without a restart: models already loaded change on the hero's next load (the next match, say)")
        .into())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn req(src: &str, dst: &str) -> Req {
        Req { id: "x".into(), src: src.into(), dst: dst.into() }
    }

    #[test]
    fn rules_use_source_paths_and_first_wins() {
        let reqs = vec![
            req("models/items/cm/arms.vmdl_c", "models/heroes/cm/cuffs.vmdl_c"),
            req("models/items/cm/other.vmdl_c", "models/heroes/cm/cuffs.vmdl_c"),
            req("materials/a.vmat_c", "materials/b.vmat_c"),
            req("same.vpcf_c", "same.vpcf_c"),
        ];
        let (text, n) = config_text(&reqs, &HashMap::new());
        assert_eq!(n, 2);
        assert!(text.contains("models/heroes/cm/cuffs.vmdl|models/items/cm/arms.vmdl\n"));
        assert!(!text.contains("other"));
        assert!(text.contains("materials/b.vmat|materials/a.vmat\n"));
        assert!(!text.contains("same.vpcf"));
    }

    #[test]
    fn hero_item_swaps_name_their_hero() {
        let reqs = vec![
            Req { id: "Twilight Schism".into(), src: "models/items/luna/schism.vmdl_c".into(), dst: "models/heroes/luna/luna_weapon.vmdl_c".into() },
            Req { id: "Mythical Courier".into(), src: "models/courier/a.vmdl_c".into(), dst: "models/courier/b.vmdl_c".into() },
        ];
        let heroes: HashMap<String, Vec<String>> = [("Twilight Schism".to_string(), vec!["npc_dota_hero_luna".to_string()])].into();
        let (text, _) = config_text(&reqs, &heroes);
        assert!(text.contains("models/heroes/luna/luna_weapon.vmdl|models/items/luna/schism.vmdl|npc_dota_hero_luna\n"));
        assert!(text.contains("models/courier/b.vmdl|models/courier/a.vmdl\n"));
    }
}
